/*
 * Generates LiberationSansMetrics.java (package klimt.drawing.font) from the
 * Liberation Sans TTF files embedded in the TeaVM C build, and from the widths
 * of Java's SansSerif measured on Windows (sansserif-windows.txt, written by
 * MeasureLogicalFonts.java).
 *
 * Usage, from the repository root (JDK 11+, no build needed):
 *
 *   java tools/font-metrics/GenerateFontMetrics.java
 *
 * It reads the TrueType tables directly (head, hhea, hmtx, cmap), which is
 * what Java2D measures with fractional metrics: no kerning, no ligatures, the
 * advance of a character is its glyph's advance width scaled by size / unitsPerEm.
 * StringBounderEmbeddedFontTest checks the result against Java2D.
 */

import java.io.IOException;
import java.io.Writer;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.HashMap;
import java.util.Map;

public class GenerateFontMetrics {

	private static final Path FONTS = Paths.get("src/teavm-c/native/fonts");
	private static final Path OUTPUT = Paths.get(
			"src/main/java/net/sourceforge/plantuml/klimt/drawing/font/LiberationSansMetrics.java");

	private static final Path MEASURED = Paths.get("tools/font-metrics/sansserif-windows.txt");

	private static final String[][] STYLES = { //
			{ "REGULAR", "LiberationSans-Regular.ttf" }, //
			{ "BOLD", "LiberationSans-Bold.ttf" }, //
			{ "ITALIC", "LiberationSans-Italic.ttf" }, //
			{ "BOLD_ITALIC", "LiberationSans-BoldItalic.ttf" } };

	public static void main(String[] args) throws IOException {
		final StringBuilder sb = new StringBuilder();
		sb.append(new String(Files.readAllBytes(Paths.get(
				"src/main/java/net/sourceforge/plantuml/klimt/drawing/font/EmbeddedFontMetrics.java")),
				StandardCharsets.UTF_8).substring(0, licenseEnd()));
		sb.append("package net.sourceforge.plantuml.klimt.drawing.font;\n\n");
		sb.append("/**\n");
		sb.append(" * Advance widths and vertical metrics of Liberation Sans 2.1.5 (SIL Open Font\n");
		sb.append(" * License 1.1), whose metrics are the same as Arial's.\n");
		sb.append(" *\n");
		sb.append(" * <p>\n");
		sb.append(" * Generated by tools/font-metrics/GenerateFontMetrics.java from the TTF files\n");
		sb.append(" * of src/teavm-c/native/fonts and tools/font-metrics/sansserif-windows.txt:\n");
		sb.append(" * do not edit.\n");
		sb.append(" */\n");
		sb.append("final class LiberationSansMetrics {\n\n");
		sb.append("\tprivate LiberationSansMetrics() {\n\t}\n");
		for (String[] style : STYLES) {
			final Font font = new Font(ByteBuffer.wrap(Files.readAllBytes(FONTS.resolve(style[1]))));
			sb.append("\n\t// ").append(style[1]).append(": ").append(font.advances.length())
					.append(" characters\n");
			sb.append("\tstatic final EmbeddedFontMetrics ").append(style[0])
					.append(" = new EmbeddedFontMetrics(").append(font.unitsPerEm).append(", ").append(font.ascent)
					.append(", ").append(font.descent).append(", ").append(font.lineGap).append(", ")
					.append(font.missingAdvance).append(",\n");
			appendLiteral(sb, font.ranges.toString());
			sb.append(",\n");
			appendLiteral(sb, font.advances.toString());
			sb.append(");\n");
		}
		appendMeasuredWidths(sb);
		sb.append("\n}\n");
		try (Writer w = Files.newBufferedWriter(OUTPUT, StandardCharsets.UTF_8)) {
			w.write(sb.toString());
		}
		System.out.println("Written " + OUTPUT);
	}

	// The widths measured by MeasureLogicalFonts: ranges of code points (first,
	// last, index of their widths), and the distinct widths of the 4 styles
	private static void appendMeasuredWidths(StringBuilder sb) throws IOException {
		final StringBuilder ranges = new StringBuilder();
		final StringBuilder widths = new StringBuilder();
		final Map<String, Integer> indexes = new HashMap<>();
		final StringBuilder comment = new StringBuilder();
		int count = 0;
		for (String line : Files.readAllLines(MEASURED, StandardCharsets.UTF_8)) {
			if (line.startsWith("# Java "))
				comment.append(line.substring(2));
			if (line.startsWith("#") || line.trim().isEmpty())
				continue;
			final String[] fields = line.trim().split(" +");
			if (fields.length != 6)
				throw new IllegalArgumentException("Bad line: " + line);
			final int first = Integer.parseInt(fields[0], 16);
			final int last = Integer.parseInt(fields[1], 16);
			final String key = fields[2] + " " + fields[3] + " " + fields[4] + " " + fields[5];
			Integer index = indexes.get(key);
			if (index == null) {
				index = indexes.size();
				indexes.put(key, index);
				for (int i = 2; i < 6; i++)
					widths.append(fields[i].equals("=") ? '\uffff' : (char) Integer.parseInt(fields[i]));
			}
			ranges.append((char) first).append((char) last).append((char) (int) index);
			count += last - first + 1;
		}
		sb.append("\n\t// Java's SansSerif on Windows, where it differs from Liberation Sans (").append(count)
				.append(" characters)\n");
		sb.append("\t// Measured with ").append(comment).append('\n');
		sb.append("\tstatic final MeasuredWidths WINDOWS_SANS_SERIF = new MeasuredWidths(\n");
		appendLiteral(sb, ranges.toString());
		sb.append(",\n");
		appendLiteral(sb, widths.toString());
		sb.append(");\n");
	}

	// The license header of the existing sources ends with the line " */\n"
	private static int licenseEnd() throws IOException {
		final String s = new String(Files.readAllBytes(Paths.get(
				"src/main/java/net/sourceforge/plantuml/klimt/drawing/font/EmbeddedFontMetrics.java")),
				StandardCharsets.UTF_8);
		return s.indexOf("\n */\n") + 5;
	}

	// A string literal split in lines of 16 characters (one constant for javac)
	private static void appendLiteral(StringBuilder sb, String s) {
		for (int i = 0; i < s.length(); i += 16) {
			sb.append(i == 0 ? "\t\t\t\"" : "\t\t\t\t\t+ \"");
			for (int j = i; j < Math.min(s.length(), i + 16); j++) {
				final int c = s.charAt(j);
				// Octal below 0x80: javac decodes Unicode escapes before parsing, so the escape
				// of a line feed, a quote or a backslash would break the literal
				sb.append(c < 0x80 ? String.format("\\%03o", c) : String.format("\\u%04x", c));
			}
			sb.append('"');
			if (i + 16 < s.length())
				sb.append('\n');
		}
	}

	static class Font {
		int unitsPerEm;
		int ascent;
		int descent;
		int lineGap;
		int missingAdvance;
		// Pairs of characters: first and last code point of each range of mapped characters
		final StringBuilder ranges = new StringBuilder();
		// One character per mapped code point, in the order of the ranges: its advance width
		final StringBuilder advances = new StringBuilder();

		Font(ByteBuffer ttf) {
			final int head = table(ttf, "head");
			final int hhea = table(ttf, "hhea");
			final int hmtx = table(ttf, "hmtx");
			unitsPerEm = ttf.getShort(head + 18) & 0xFFFF;
			ascent = ttf.getShort(hhea + 4);
			descent = -ttf.getShort(hhea + 6);
			lineGap = ttf.getShort(hhea + 8);
			final int numberOfHMetrics = ttf.getShort(hhea + 34) & 0xFFFF;
			final int[] glyphs = cmap(ttf);
			missingAdvance = advance(ttf, hmtx, numberOfHMetrics, 0);
			int start = -1;
			for (int cp = 0; cp <= 0x10000; cp++) {
				final boolean mapped = cp < 0x10000 && glyphs[cp] != 0;
				if (mapped && start == -1)
					start = cp;
				if (mapped == false && start != -1) {
					ranges.append((char) start).append((char) (cp - 1));
					start = -1;
				}
				if (mapped)
					advances.append((char) advance(ttf, hmtx, numberOfHMetrics, glyphs[cp]));
			}
		}

		private static int advance(ByteBuffer ttf, int hmtx, int numberOfHMetrics, int glyph) {
			final int index = Math.min(glyph, numberOfHMetrics - 1);
			return ttf.getShort(hmtx + 4 * index) & 0xFFFF;
		}

		private static int table(ByteBuffer ttf, String tag) {
			final int numTables = ttf.getShort(4) & 0xFFFF;
			for (int i = 0; i < numTables; i++) {
				final int entry = 12 + 16 * i;
				final String name = new String(new byte[] { ttf.get(entry), ttf.get(entry + 1), ttf.get(entry + 2),
						ttf.get(entry + 3) }, StandardCharsets.ISO_8859_1);
				if (name.equals(tag))
					return ttf.getInt(entry + 8);
			}
			throw new IllegalArgumentException("No table " + tag);
		}

		// Glyph index of every BMP code point, from the Windows Unicode BMP subtable (format 4)
		private static int[] cmap(ByteBuffer ttf) {
			final int cmap = table(ttf, "cmap");
			final int numSubtables = ttf.getShort(cmap + 2) & 0xFFFF;
			for (int i = 0; i < numSubtables; i++) {
				final int platform = ttf.getShort(cmap + 4 + 8 * i) & 0xFFFF;
				final int encoding = ttf.getShort(cmap + 6 + 8 * i) & 0xFFFF;
				final int offset = cmap + ttf.getInt(cmap + 8 + 8 * i);
				if (platform == 3 && encoding == 1 && (ttf.getShort(offset) & 0xFFFF) == 4)
					return format4(ttf, offset);
			}
			throw new IllegalArgumentException("No Windows Unicode BMP cmap subtable");
		}

		private static int[] format4(ByteBuffer ttf, int offset) {
			final int[] result = new int[0x10000];
			final int segCount = (ttf.getShort(offset + 6) & 0xFFFF) / 2;
			final int endCodes = offset + 14;
			final int startCodes = endCodes + 2 * segCount + 2;
			final int idDeltas = startCodes + 2 * segCount;
			final int idRangeOffsets = idDeltas + 2 * segCount;
			for (int seg = 0; seg < segCount; seg++) {
				final int end = ttf.getShort(endCodes + 2 * seg) & 0xFFFF;
				final int start = ttf.getShort(startCodes + 2 * seg) & 0xFFFF;
				final int delta = ttf.getShort(idDeltas + 2 * seg);
				final int rangeOffsetAddress = idRangeOffsets + 2 * seg;
				final int rangeOffset = ttf.getShort(rangeOffsetAddress) & 0xFFFF;
				for (int c = start; c <= end && c != 0xFFFF; c++) {
					int glyph;
					if (rangeOffset == 0) {
						glyph = (c + delta) & 0xFFFF;
					} else {
						glyph = ttf.getShort(rangeOffsetAddress + rangeOffset + 2 * (c - start)) & 0xFFFF;
						if (glyph != 0)
							glyph = (glyph + delta) & 0xFFFF;
					}
					result[c] = glyph;
				}
			}
			return result;
		}
	}

}
