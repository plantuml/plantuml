/*
 * Measures, with Java on Windows, every character for which Java's logical
 * font "SansSerif" does not measure as StringBounderEmbeddedFont does, and
 * writes the differences to tools/font-metrics/sansserif-windows.txt.
 *
 * Why: on Windows, Java's "SansSerif" is a composite font. Arial only provides
 * the characters outside its exclusion ranges (fontconfig.properties:
 * exclusion.alphabetic=0700-1e9f,1f00-20ab,20ad-f8ff), so the en dash, the
 * typographic quotes, the ellipsis... come from fallback fonts (Segoe UI
 * Symbol, MingLiU...), with their own widths, even though Arial has them. And
 * characters Arial lacks are not exactly as wide as PlantUML's width table.
 * Only Java on Windows knows these widths: they are measured here once, on a
 * Windows with a Western locale, and kept as data.
 *
 * Usage, on Windows, from the repository root (needs the compiled classes):
 *
 *   gradlew compileJava
 *   java -cp build/classes/java/main tools/font-metrics/MeasureLogicalFonts.java
 *
 * Each line of the output is a range of consecutive code points that measure
 * the same: first and last code point, then for the regular, bold, italic and
 * bold italic styles the width Java gives at size 2048 (that is, in 2048ths of
 * the font size), or "=" when it is the same as StringBounderEmbeddedFont.
 * GenerateFontMetrics turns it into a table of LiberationSansMetrics.
 */

import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Locale;

import net.sourceforge.plantuml.FileFormat;
import net.sourceforge.plantuml.klimt.drawing.font.StringBounderEmbeddedFont;
import net.sourceforge.plantuml.klimt.font.StringBounder;
import net.sourceforge.plantuml.klimt.font.UFont;
import net.sourceforge.plantuml.klimt.font.UFontFace;
import net.sourceforge.plantuml.klimt.font.UFontFactory;

public class MeasureLogicalFonts {

	private static final Path OUTPUT = Paths.get("tools/font-metrics/sansserif-windows.txt");

	private static final int SIZE = 2048;

	public static void main(String[] args) throws IOException {
		if (System.getProperty("os.name").startsWith("Windows") == false)
			throw new IllegalStateException("Java's SansSerif is only Arial on Windows: run this on Windows");

		final StringBounder awt = FileFormat.PNG.getDefaultStringBounder();
		// Without the widths measured by a previous run, which this run measures again
		final StringBounder embedded = StringBounderEmbeddedFont.withoutWindowsWidths(FileFormat.PNG);
		final UFontFace[] faces = { UFontFace.normal(), UFontFace.bold(), UFontFace.italic(),
				UFontFace.boldItalic() };
		final UFont[] fonts = new UFont[faces.length];
		for (int i = 0; i < faces.length; i++)
			fonts[i] = UFontFactory.build("SansSerif", faces[i], SIZE);

		final StringBuilder sb = new StringBuilder();
		sb.append("# Widths of Java's logical font SansSerif on Windows, in 2048ths of the font size,\n");
		sb.append("# where they differ from StringBounderEmbeddedFont (\"=\": same).\n");
		sb.append("# Generated by tools/font-metrics/MeasureLogicalFonts.java: do not edit.\n");
		sb.append("# Java ").append(System.getProperty("java.version")).append(", ")
				.append(System.getProperty("os.name")).append(' ').append(System.getProperty("os.version"))
				.append(", locale ").append(Locale.getDefault()).append('\n');
		sb.append("# first and last code point, regular, bold, italic, bold italic\n");

		int count = 0;
		int first = -1;
		int last = -1;
		String widths = null;
		for (int cp = 0; cp <= 0x10000; cp++) {
			String current = null;
			if (cp <= 0xFFFF && Character.isSurrogate((char) cp) == false) {
				final String text = String.valueOf((char) cp);
				final StringBuilder line = new StringBuilder();
				boolean different = false;
				for (UFont font : fonts) {
					final double java = awt.calculateDimension(font, text).getWidth();
					final double ours = embedded.calculateDimension(font, text).getWidth();
					if (java == ours) {
						line.append(" =");
					} else {
						if (java != Math.rint(java))
							throw new IllegalStateException("Not a whole number of units: " + cp + " " + java);
						line.append(' ').append((long) java);
						different = true;
					}
				}
				if (different) {
					current = line.toString();
					count++;
				}
			}
			// Consecutive code points with the same widths share one line
			if (widths != null && (current == null || current.equals(widths) == false || cp != last + 1)) {
				sb.append(String.format("%04x %04x", first, last)).append(widths).append('\n');
				widths = null;
			}
			if (current != null) {
				if (widths == null) {
					first = cp;
					widths = current;
				}
				last = cp;
			}
		}

		try (Writer w = Files.newBufferedWriter(OUTPUT, StandardCharsets.UTF_8)) {
			w.write(sb.toString());
		}
		System.out.println(count + " characters differ, written to " + OUTPUT);
	}

}
