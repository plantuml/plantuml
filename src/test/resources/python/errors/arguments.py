# Wrong arguments to the builtins, the methods and the math module.
# Only the type of the exception is compared, never its message.
import math

failures = []

def check(exc, f):
    try:
        f()
    except exc:
        return
    except Exception as e:
        failures.append(("wrong exception", f, e))
        return
    failures.append(("no exception", f, None))

# --- arity ---
for f in [lambda: len(), lambda: len([], [])]:
    check(TypeError, f)
check(TypeError, lambda: abs())
