check(TypeError, lambda: enumerate())
check(TypeError, lambda: reversed())
check(TypeError, lambda: min())
check(TypeError, lambda: max())
check(TypeError, lambda: sum())
check(TypeError, lambda: math.sqrt())
check(TypeError, lambda: math.sqrt(1, 2))
check(TypeError, lambda: math.atan2(1))
check(TypeError, lambda: "abc".upper(1))
check(TypeError, lambda: "abc".split(1, 2, 3))
check(TypeError, lambda: "abc".find())
check(TypeError, lambda: "abc".replace("a"))
