/*
 * Build-time tool of embed_resources.cmake: writes a C file that embeds files
 * in the executable.
 *
 *   plantuml_embed_tool <output.c> <list>
 *
 * Every line of <list> is "<name>=<file>"; the C file defines the table of
 * plantuml_resources.h with these names and the bytes of these files.
 *
 * It is a program, not a CMake script, because CMake takes minutes (and
 * gigabytes) to turn megabytes into C source.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int fail(const char* what, const char* path) {
	fprintf(stderr, "plantuml_embed_tool: %s %s\n", what, path);
	return 1;
}

static int write_array(FILE* out, int index, const char* path) {
	FILE* in = fopen(path, "rb");
	unsigned char buffer[4096];
	size_t n;
	int column = 0;
	if (in == NULL)
		return fail("cannot read", path);
	/* One byte more, so that an empty file is still a valid array */
	fprintf(out, "static const unsigned char plantuml_resource_%d[] = {\n", index);
	while ((n = fread(buffer, 1, sizeof buffer, in)) > 0) {
		size_t i;
		for (i = 0; i < n; i++) {
			fprintf(out, "%u,", buffer[i]);
			if (++column == 32) {
				fputc('\n', out);
				column = 0;
			}
		}
	}
	fprintf(out, "0};\n");
	fclose(in);
	return 0;
}

static long file_size(const char* path) {
	FILE* in = fopen(path, "rb");
	long size;
	if (in == NULL)
		return -1;
	fseek(in, 0, SEEK_END);
	size = ftell(in);
	fclose(in);
	return size;
}

int main(int argc, char** argv) {
	FILE* list;
	FILE* out;
	char line[8192];
	int index = 0;
	int pass;

	if (argc != 3)
		return fail("usage: plantuml_embed_tool <output.c> <list>", "");
	out = fopen(argv[1], "wb");
	if (out == NULL)
		return fail("cannot write", argv[1]);
	fprintf(out, "/* Generated by plantuml_embed_tool, do not edit */\n#include \"plantuml_resources.h\"\n\n");

	/* Pass 0: the arrays; pass 1: the table */
	for (pass = 0; pass < 2; pass++) {
		index = 0;
		list = fopen(argv[2], "rb");
		if (list == NULL)
			return fail("cannot read", argv[2]);
		if (pass == 1)
			fprintf(out, "\nconst plantuml_resource plantuml_resources[] = {\n");
		while (fgets(line, sizeof line, list) != NULL) {
			char* equals;
			size_t len = strlen(line);
			while (len > 0 && (line[len - 1] == '\n' || line[len - 1] == '\r'))
				line[--len] = 0;
			if (len == 0)
				continue;
			equals = strchr(line, '=');
			if (equals == NULL)
				return fail("bad line", line);
			*equals = 0;
			if (pass == 0) {
				if (write_array(out, index, equals + 1) != 0)
					return 1;
			} else {
				long size = file_size(equals + 1);
				if (size < 0)
					return fail("cannot read", equals + 1);
				fprintf(out, "\t{\"%s\", plantuml_resource_%d, %ld},\n", line, index, size);
			}
			index++;
		}
		fclose(list);
	}
	fprintf(out, "\t{0, 0, 0}\n};\nconst int32_t plantuml_resources_count = %d;\n", index);
	fclose(out);
	return 0;
}
