package net.sourceforge.plantuml.math;

import net.sourceforge.plantuml.klimt.color.HColor;
import net.sourceforge.plantuml.klimt.drawing.UGraphic;
import net.sourceforge.plantuml.klimt.geom.XDimension2D;

/**
 * A formula that is ready to be drawn on a {@link UGraphic}: its size, and how
 * to draw it. Hides the JLaTeXMath classes, which are not in every license
 * variant.
 */
public interface MathDrawing {

	public XDimension2D getDimension();

	/**
	 * Draws the formula with its top left corner at the origin of the UGraphic.
	 * The color is given as is to the UGraphic, which maps it as for any other
	 * shape; a formula that sets its own colors (\color) overrides it.
	 */
	public void draw(UGraphic ug, HColor foreground);

}
